"""check_docs — doc linter and index generator for bootstrap-kit projects.

Usage: check_docs.py [--fix] [--root PATH] [--stale-hours N]
Exit status 1 if any E-code finding, else 0. Warnings (W-codes) print but pass.

Codes (the CODES table below is the same list, for tooling):
  E001 cited file missing              E009 planned or active milestone without exit criteria
  E002 cited section missing           E010 moved pointer does not resolve
  E003 milestone index missing/stale   E011 file is not valid UTF-8
  E004 ADR index missing/stale         E012 config invalid; defaults used for the bad key
  E005 placeholder or TBD left in doc  E013 status outside its object's vocabulary
  E006 plan and feature disagree       E014 design doc header missing or status invalid
  E007 done milestone not complete     E015 design doc has no ## Changelog
  E008 depends on sketch/dropped/unknown  E016 phase rule broken
  W001 claim stale or unstamped        W004 milestone outside 3-10 features
  W002 in-progress plan, unticked dep  W005 evidence file not written yet
  W003 generated file differs          W006 AGENTS.md over 120 lines
  W007 cited project file not written yet (no CURRENT.md, bootstrap in progress)
"""
